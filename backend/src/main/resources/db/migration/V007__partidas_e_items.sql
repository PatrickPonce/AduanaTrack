CREATE TABLE item_factura (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despacho_id     BIGINT         NOT NULL REFERENCES despacho (id),
    -- Posición en la factura (1, 2, 3…), asignada por el backend.
    numero          INTEGER        NOT NULL CHECK (numero > 0),
    descripcion     VARCHAR(500)   NOT NULL,
    cantidad        NUMERIC(15, 3) NOT NULL CHECK (cantidad > 0),
    unidad          VARCHAR(10)    NOT NULL,
    -- USD, 2 decimales.
    valor_fob       NUMERIC(15, 2) NOT NULL CHECK (valor_fob > 0),
    partida_id      BIGINT REFERENCES partida_referencial (id),
    clasificado_por BIGINT REFERENCES usuario (id),
    clasificado_en  TIMESTAMP,
    -- Diferida para poder renumerar los ítems de un despacho en una sola transacción.
    CONSTRAINT uq_item_factura_numero UNIQUE (despacho_id, numero) DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX ix_item_factura_despacho ON item_factura (despacho_id);
CREATE INDEX ix_item_factura_partida ON item_factura (partida_id);
