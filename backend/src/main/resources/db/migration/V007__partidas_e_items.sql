-- Catálogo referencial de partidas arancelarias e ítems de la factura comercial
-- (HU-07 · T-07.1 · SCRUM-58). Un solo V007 con las dos tablas para que T-07.2 (ítems, Patrick)
-- no cree otra migración. El catálogo es interno: no se conecta al Arancel de SUNAT.

CREATE TABLE partida_referencial (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 10 dígitos; se muestra como 8482.10.00.00.
    codigo          VARCHAR(10)   NOT NULL UNIQUE CHECK (codigo ~ '^[0-9]{10}$'),
    descripcion     VARCHAR(300)  NOT NULL,
    -- Porcentaje (6.00 = 6 %).
    tasa_ad_valorem NUMERIC(5, 2) NOT NULL CHECK (tasa_ad_valorem >= 0 AND tasa_ad_valorem <= 100),
    -- Descripción en minúsculas y sin tildes para el buscador (se llena más abajo).
    busqueda        VARCHAR(300)  NOT NULL DEFAULT '',
    activo          BOOLEAN       NOT NULL DEFAULT TRUE
);

