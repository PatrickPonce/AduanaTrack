-- Resultado de la inspección aduanera (HU-12 · T-12.1). El agente registra lo que verificó en la
-- inspección física del depósito: un checklist de ítems, observaciones generales y el acta en PDF (opcional).
-- Es V016 y no V013: en Neon ya corrieron V014 y V015, y Flyway rechaza una versión menor a la última aplicada.
-- Una inspección con observaciones puede repetirse, por eso hay una fila por inspección y no una por despacho.

CREATE TABLE inspeccion_despacho (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despacho_id   BIGINT       NOT NULL REFERENCES despacho (id),
    -- CONFORME o CON_OBSERVACIONES; sin CHECK, igual que despacho.estado: los valores viven en el enum.
    resultado     VARCHAR(20)  NOT NULL,
    observaciones VARCHAR(500),
    -- Acta (PDF opcional): nombre original y ruta relativa al directorio de documentos.
    acta_nombre   VARCHAR(255),
    acta_ruta     VARCHAR(255),
    registrada_por BIGINT      NOT NULL REFERENCES usuario (id),
    registrada_en  TIMESTAMP   NOT NULL
);

CREATE INDEX ix_inspeccion_despacho_despacho ON inspeccion_despacho (despacho_id, registrada_en, id);

CREATE TABLE inspeccion_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspeccion_id BIGINT       NOT NULL REFERENCES inspeccion_despacho (id),
    orden         INT          NOT NULL,
    descripcion   VARCHAR(120) NOT NULL,
    conforme      BOOLEAN      NOT NULL,
    -- Solo en el ítem que no es conforme.
    observacion   VARCHAR(255)
);

CREATE INDEX ix_inspeccion_item_inspeccion ON inspeccion_item (inspeccion_id, orden);
