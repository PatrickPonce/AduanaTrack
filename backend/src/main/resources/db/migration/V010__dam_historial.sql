-- Historial de rectificaciones del N° de DAM (HU-09 · SCRUM-67, regla de negocio 3): si el número
-- o la fecha de numeración se corrigen, se conserva el valor anterior, el motivo, el usuario y la fecha.

CREATE TABLE dam_historial (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despacho_id     BIGINT       NOT NULL REFERENCES despacho (id),
    numero_anterior VARCHAR(30)  NOT NULL,
    fecha_anterior  DATE,
    numero_nuevo    VARCHAR(30)  NOT NULL,
    fecha_nueva     DATE,
    motivo          VARCHAR(200) NOT NULL,
    rectificado_por BIGINT       NOT NULL REFERENCES usuario (id),
    rectificado_en  TIMESTAMP    NOT NULL
);

CREATE INDEX ix_dam_historial_despacho ON dam_historial (despacho_id, rectificado_en, id);
