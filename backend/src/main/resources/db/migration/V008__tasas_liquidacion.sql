-- T-08.2 (SCRUM-64 · Patrick): liquidación referencial y pago de tributos.
-- Una liquidación vigente por despacho: volver a generarla antes del pago actualiza la misma fila.
-- Guarda las tasas usadas para que el desglose no cambie si el PO ajusta parametro_sistema.

CREATE TABLE liquidacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despacho_id     BIGINT         NOT NULL UNIQUE REFERENCES despacho (id),
    -- USD, 2 decimales.
    fob             NUMERIC(15, 2) NOT NULL CHECK (fob > 0),
    flete           NUMERIC(15, 2) NOT NULL CHECK (flete >= 0),
    seguro          NUMERIC(15, 2) NOT NULL CHECK (seguro >= 0),
    cif             NUMERIC(15, 2) NOT NULL,
    ad_valorem      NUMERIC(15, 2) NOT NULL,
    igv             NUMERIC(15, 2) NOT NULL,
    ipm             NUMERIC(15, 2) NOT NULL,
    percepcion      NUMERIC(15, 2) NOT NULL,
    total           NUMERIC(15, 2) NOT NULL,
    -- Porcentajes (16 = 16 %).
    tasa_igv        NUMERIC(6, 2)  NOT NULL,
    tasa_ipm        NUMERIC(6, 2)  NOT NULL,
    tasa_percepcion NUMERIC(6, 2)  NOT NULL,
    generado_por    BIGINT         NOT NULL REFERENCES usuario (id),
    generado_en     TIMESTAMP      NOT NULL
);

-- Pago hecho fuera del sistema (HU-08, CA3). Uno por despacho.
CREATE TABLE pago_tributos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despacho_id       BIGINT         NOT NULL UNIQUE REFERENCES despacho (id),
    fecha             DATE           NOT NULL,
    monto             NUMERIC(15, 2) NOT NULL CHECK (monto > 0),
    medio_pago        VARCHAR(30)    NOT NULL,
    numero_operacion  VARCHAR(50)    NOT NULL,
    registrado_por    BIGINT         NOT NULL REFERENCES usuario (id),
    registrado_en     TIMESTAMP      NOT NULL
);
