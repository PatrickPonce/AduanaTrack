-- Notificaciones y alertas del despacho (HU-14 · T-14.1 · SCRUM-90). Cada fila es de un solo usuario: el
-- agente responsable (despacho.agente_id) o el usuario al que otro servicio decida avisar.
-- Es V015 y no V014: la numeración se corrió una posición porque V011 ya la ocupa el Arancel de Aduanas 2022.

CREATE TABLE notificacion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL REFERENCES usuario (id),
    -- Nulo en los avisos que no son de un despacho (p. ej. una carta poder por vencer).
    despacho_id BIGINT REFERENCES despacho (id),
    -- Sin CHECK, igual que despacho.estado: los valores viven en los enums TipoNotificacion y Severidad.
    tipo        VARCHAR(40)  NOT NULL,
    -- CRITICA, ALTA o INFO.
    severidad   VARCHAR(10)  NOT NULL,
    titulo      VARCHAR(150) NOT NULL,
    mensaje     VARCHAR(500) NOT NULL,
    leida       BOOLEAN      NOT NULL DEFAULT FALSE,
    creada_en   TIMESTAMP    NOT NULL,
    leida_en    TIMESTAMP
);

-- La bandeja y el contador de la campana siempre filtran por usuario y por leída.
CREATE INDEX ix_notificacion_usuario ON notificacion (usuario_id, leida, creada_en DESC, id DESC);

-- Canal preferido para recibir las notificaciones: SISTEMA, CORREO o AMBOS.
ALTER TABLE usuario
    ADD COLUMN canal_notificacion VARCHAR(10) NOT NULL DEFAULT 'SISTEMA';
