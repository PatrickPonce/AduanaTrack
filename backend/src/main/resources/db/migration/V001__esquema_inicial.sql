-- Esquema inicial del Sprint 1 (T-00.4 · SCRUM-24): 13 tablas.
-- Debe coincidir con las entidades JPA (spring.jpa.hibernate.ddl-auto=validate).
-- Las marcas de tiempo van sin zona: la aplicación trabaja en hora de Lima.

CREATE TABLE rol (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20)  NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE usuario (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario           VARCHAR(50)  NOT NULL UNIQUE,
    correo            VARCHAR(150) NOT NULL UNIQUE,
    nombre            VARCHAR(150) NOT NULL,
    password_hash     VARCHAR(100) NOT NULL,
    rol_id            BIGINT       NOT NULL REFERENCES rol (id),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    intentos_fallidos INTEGER      NOT NULL DEFAULT 0,
    bloqueado_hasta   TIMESTAMP
);

-- El login busca por usuario o correo sin distinguir mayúsculas.
CREATE UNIQUE INDEX ux_usuario_usuario_lower ON usuario (LOWER(usuario));
CREATE UNIQUE INDEX ux_usuario_correo_lower ON usuario (LOWER(correo));

CREATE TABLE auditoria_acceso (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_ingresado VARCHAR(150) NOT NULL,
    -- Nulo cuando el usuario ingresado no existe.
    usuario_id        BIGINT REFERENCES usuario (id),
    ip                VARCHAR(45),
    user_agent        VARCHAR(500),
    resultado         VARCHAR(20)  NOT NULL CHECK (resultado IN ('EXITO', 'FALLIDO', 'BLOQUEADO')),
    fecha             TIMESTAMP    NOT NULL
);

CREATE INDEX ix_auditoria_acceso_fecha ON auditoria_acceso (fecha);
CREATE INDEX ix_auditoria_acceso_usuario ON auditoria_acceso (usuario_id);

CREATE TABLE parametro_sistema (
    clave       VARCHAR(50)  PRIMARY KEY,
    valor       VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255)
);

CREATE TABLE regimen_aduanero (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(10)  NOT NULL UNIQUE,
    descripcion VARCHAR(150) NOT NULL,
    activo      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE aduana (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(10)  NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    activo BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE cliente (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc            VARCHAR(11)  NOT NULL UNIQUE,
    razon_social   VARCHAR(200) NOT NULL,
    direccion      VARCHAR(250),
    correo         VARCHAR(150),
    telefono       VARCHAR(20),
    contacto       VARCHAR(150),
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en      TIMESTAMP    NOT NULL,
    actualizado_en TIMESTAMP    NOT NULL
);

CREATE TABLE cliente_historial (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id     BIGINT      NOT NULL REFERENCES cliente (id),
    campo          VARCHAR(50) NOT NULL,
    valor_anterior VARCHAR(250),
    valor_nuevo    VARCHAR(250),
    usuario_id     BIGINT      NOT NULL REFERENCES usuario (id),
    fecha          TIMESTAMP   NOT NULL
);

CREATE INDEX ix_cliente_historial_cliente ON cliente_historial (cliente_id, fecha DESC);

CREATE TABLE carta_poder (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id         BIGINT       NOT NULL REFERENCES cliente (id),
    fecha_emision      DATE         NOT NULL,
    fecha_vencimiento  DATE         NOT NULL,
    ruta_archivo       VARCHAR(255) NOT NULL,
    nombre_archivo     VARCHAR(255) NOT NULL,
    tamano_bytes       BIGINT       NOT NULL,
    sha256             VARCHAR(64)  NOT NULL,
    alerta_generada_en TIMESTAMP
);

CREATE INDEX ix_carta_poder_cliente ON carta_poder (cliente_id, fecha_vencimiento);

CREATE TABLE despacho (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- DESP-AAAA-####; nulo mientras el despacho es borrador.
    numero                VARCHAR(20) UNIQUE,
    cliente_id            BIGINT      NOT NULL REFERENCES cliente (id),
    regimen_id            BIGINT REFERENCES regimen_aduanero (id),
    aduana_id             BIGINT REFERENCES aduana (id),
    referencia_cliente    VARCHAR(100),
    descripcion_mercancia VARCHAR(1000),
    -- Sin CHECK: los estados de los Sprints 2 y 3 se agregan al enum EstadoDespacho.
    estado                VARCHAR(30) NOT NULL,
    canal_control         VARCHAR(20),
    fecha_levante         DATE,
    agente_id             BIGINT      NOT NULL REFERENCES usuario (id),
    creado_en             TIMESTAMP   NOT NULL
);

CREATE INDEX ix_despacho_cliente ON despacho (cliente_id);
CREATE INDEX ix_despacho_aduana ON despacho (aduana_id);
CREATE INDEX ix_despacho_estado ON despacho (estado);

CREATE TABLE correlativo_despacho (
    anio          INTEGER PRIMARY KEY,
    ultimo_numero INTEGER NOT NULL
);

CREATE TABLE embarque (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despacho_id             BIGINT       NOT NULL UNIQUE REFERENCES despacho (id),
    numero_bl               VARCHAR(50)  NOT NULL,
    tipo_bl                 VARCHAR(10)  NOT NULL CHECK (tipo_bl IN ('MASTER', 'HOUSE')),
    naviera                 VARCHAR(100) NOT NULL,
    buque                   VARCHAR(100),
    puerto_embarque         VARCHAR(100) NOT NULL,
    puerto_descarga         VARCHAR(100),
    fecha_embarque          DATE,
    fecha_eta               DATE         NOT NULL,
    fecha_limite_almacenaje DATE         NOT NULL
);

CREATE TABLE contenedor (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    embarque_id BIGINT      NOT NULL REFERENCES embarque (id) ON DELETE CASCADE,
    numero      VARCHAR(11) NOT NULL,
    tipo        VARCHAR(10),
    precinto    VARCHAR(30),
    CONSTRAINT uq_contenedor_embarque_numero UNIQUE (embarque_id, numero)
);
