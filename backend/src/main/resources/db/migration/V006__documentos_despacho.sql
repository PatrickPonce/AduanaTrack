-- Documentos del despacho (HU-06 · T-06.1 · SCRUM-53): catálogo de documentos requeridos y
-- versiones de cada documento cargado. Al reemplazar, la versión anterior queda con
-- vigente = FALSE y no se borra (CA3).

CREATE TABLE tipo_documento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(40)  NOT NULL UNIQUE,
    nombre      VARCHAR(100) NOT NULL,
    obligatorio BOOLEAN      NOT NULL,
    -- Orden en la tabla «Documentos requeridos del despacho».
    orden       INTEGER      NOT NULL,
    activo      BOOLEAN      NOT NULL DEFAULT TRUE
);

