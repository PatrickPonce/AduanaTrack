CREATE TABLE documento_despacho (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despacho_id       BIGINT       NOT NULL REFERENCES despacho (id),
    tipo_documento_id BIGINT       NOT NULL REFERENCES tipo_documento (id),
    version           INTEGER      NOT NULL CHECK (version > 0),
    vigente           BOOLEAN      NOT NULL,
    nombre_archivo    VARCHAR(255) NOT NULL,
    -- Relativa al directorio de documentos: {despacho_id}/{uuid}.pdf
    ruta_archivo      VARCHAR(255) NOT NULL,
    tamano_bytes      BIGINT       NOT NULL,
    sha256            VARCHAR(64)  NOT NULL,
    usuario_id        BIGINT       NOT NULL REFERENCES usuario (id),
    cargado_en        TIMESTAMP    NOT NULL,
    CONSTRAINT uq_documento_despacho_version UNIQUE (despacho_id, tipo_documento_id, version)
);

-- Una sola versión vigente por tipo de documento en cada despacho.
CREATE UNIQUE INDEX ux_documento_despacho_vigente
    ON documento_despacho (despacho_id, tipo_documento_id) WHERE vigente;
