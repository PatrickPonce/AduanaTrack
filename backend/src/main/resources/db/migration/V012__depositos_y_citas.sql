CREATE TABLE cita_despacho (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despacho_id                BIGINT       NOT NULL REFERENCES despacho (id),
    deposito_id                BIGINT       NOT NULL REFERENCES deposito (id),
    numero_cita                VARCHAR(30)  NOT NULL,
    -- INSPECCION o RETIRO.
    tipo                       VARCHAR(20)  NOT NULL,
    fecha_hora_confirmada      TIMESTAMP    NOT NULL,
    -- PROGRAMADA, REALIZADA o CANCELADA.
    estado                     VARCHAR(20)  NOT NULL,
    -- Datos del transportista: solo en las citas de retiro.
    transportista_ruc          VARCHAR(11),
    transportista_razon_social VARCHAR(150),
    transportista_placa        VARCHAR(10),
    transportista_conductor    VARCHAR(100),
    registrado_por             BIGINT       NOT NULL REFERENCES usuario (id),
    registrado_en              TIMESTAMP    NOT NULL
);

CREATE INDEX ix_cita_despacho_despacho ON cita_despacho (despacho_id, fecha_hora_confirmada, id);
