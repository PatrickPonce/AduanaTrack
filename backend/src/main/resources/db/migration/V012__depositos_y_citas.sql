-- Citas en depósito temporal o almacén (HU-11 · T-11.1 · SCRUM-78). El agente registra aquí la cita de
-- inspección o de retiro que ya coordinó en la plataforma del depósito; el sistema solo guarda la trazabilidad.
-- Es V012 y no V011 porque V011 ya la ocupa el Arancel de Aduanas 2022 en develop.

CREATE TABLE deposito (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo    VARCHAR(10)  NOT NULL UNIQUE,
    nombre    VARCHAR(120) NOT NULL,
    -- DEPOSITO_TEMPORAL o ALMACEN; sin CHECK, igual que despacho.estado: los valores viven en el enum.
    tipo      VARCHAR(20)  NOT NULL,
    direccion VARCHAR(200),
    activo    BOOLEAN      NOT NULL DEFAULT TRUE
);

