-- HU-16 · Portal del cliente: cada usuario CLIENTE queda ligado a una empresa importadora y solo ve
-- los despachos, documentos y liquidaciones de esa empresa.
-- V013 y V016 las ocupa Fabio (T-12 / T-15); esta es V017.

-- Empresa asignada al usuario. Nula para ADMIN y AGENTE, y para un CLIENTE todavía sin empresa
-- (un CLIENTE sin empresa no ve ningún despacho).
ALTER TABLE usuario
    ADD COLUMN cliente_id          BIGINT REFERENCES cliente (id),
    -- Fecha de la última asignación o cambio de empresa (pantalla "Usuarios cliente").
    ADD COLUMN cliente_asignado_en TIMESTAMP;

CREATE INDEX ix_usuario_cliente ON usuario (cliente_id);

-- Cada intento de un CLIENTE de abrir un despacho que no es de su empresa (o de entrar sin tener
-- empresa asignada). La API responde 404 «Despacho no encontrado»; aquí queda el rastro real.
CREATE TABLE acceso_denegado (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha              TIMESTAMP   NOT NULL,
    usuario_id         BIGINT      NOT NULL REFERENCES usuario (id),
    -- Id solicitado en la URL. Sin FK: el intento se guarda aunque el despacho se elimine.
    despacho_id        BIGINT      NOT NULL,
    -- Empresa dueña del despacho solicitado (nulo si el despacho no existe).
    cliente_id         BIGINT REFERENCES cliente (id),
    -- OTRA_EMPRESA, SIN_EMPRESA o BORRADOR (valores del enum MotivoAccesoDenegado).
    resultado          VARCHAR(30) NOT NULL
);

CREATE INDEX ix_acceso_denegado_fecha ON acceso_denegado (fecha DESC, id DESC);
CREATE INDEX ix_acceso_denegado_usuario ON acceso_denegado (usuario_id);

-- El usuario demo «cliente» queda asignado a una empresa que ya exista en los datos de prueba
-- (la de menor id). Si todavía no hay empresas, queda sin asignar y el administrador la asigna
-- desde «Usuarios cliente»; el script de demo (docs/despliegue.md) también la asigna.
UPDATE usuario
SET cliente_id = (SELECT MIN(id) FROM cliente WHERE activo = TRUE),
    cliente_asignado_en = CURRENT_TIMESTAMP
WHERE usuario = 'cliente'
  AND EXISTS (SELECT 1 FROM cliente WHERE activo = TRUE);
