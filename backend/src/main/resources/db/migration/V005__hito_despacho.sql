-- Línea de tiempo del despacho (HU-10 · T-10.1 · SCRUM-52). Cada cambio de estado de los
-- Sprints 2 y 3 registra aquí un hito con el usuario y la fecha.
-- tipo va sin CHECK, igual que despacho.estado: los tipos nuevos se agregan al enum TipoHito.

CREATE TABLE hito_despacho (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despacho_id BIGINT       NOT NULL REFERENCES despacho (id),
    tipo        VARCHAR(30)  NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    -- Hito que el sistema propone (p. ej. "Programar inspección física" en canal rojo).
    sugerido    BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Nulo cuando lo registra el sistema.
    usuario_id  BIGINT REFERENCES usuario (id),
    fecha       TIMESTAMP    NOT NULL
);

CREATE INDEX ix_hito_despacho_despacho ON hito_despacho (despacho_id, fecha, id);

-- Hito de apertura de los despachos que ya estaban abiertos antes de esta migración.
INSERT INTO hito_despacho (despacho_id, tipo, descripcion, sugerido, usuario_id, fecha)
SELECT id, 'APERTURA', 'Despacho abierto (' || numero || ')', FALSE, agente_id, creado_en
